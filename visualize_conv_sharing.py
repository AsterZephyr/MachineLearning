print("""
1️⃣  【局部连接 (Local Connectivity)】
    ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    • 每个输出只看输入的一小块区域
    • 不是所有输入像素都参与计算

    全连接：输出[0] 看所有36个像素
    卷积：  输出[0] 只看9个像素 (3×3窗口)

    参数从 36 减少到 9


2️⃣  【参数共享 (Parameter Sharing)】
    ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    • 同一个卷积核在不同位置重复使用
    • 所有位置共享这一套参数

    全连接：16个输出需要 16×36 = 576 个参数
    卷积：  16个输出共享 9 个参数

    参数从 576 减少到 9


3️⃣  【平移不变性 (Translation Invariance)】
    ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
    • 特征无论在哪里出现，都能被检测到
    • 因为用的是同一个检测器（卷积核）

    例：边缘检测卷积核
    • 左上角的边缘 ──→ 用这个卷积核检测
    • 右下角的边缘 ──→ 用同一个卷积核检测
    • 中间的边缘   ──→ 还是用这个卷积核检测
""")

