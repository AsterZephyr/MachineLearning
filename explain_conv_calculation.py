def manual_conv2d(X, K):
    """手动实现卷积"""
    h, w = K.shape
    out_h = X.shape[0] - h + 1
    out_w = X.shape[1] - w + 1
    Y = np.zeros((out_h, out_w))

    for i in range(out_h):
        for j in range(out_w):
            Y[i, j] = np.sum(X[i:i+h, j:j+w] * K)
    return Y

Y = manual_conv2d(X, K)
print("\n手动计算的输出：")
print(Y)

